export function getExerciseAnimation(exerciseId: string): ExerciseAnimationDef {
  if (EXERCISE_ANIMATIONS[exerciseId]) {
    return EXERCISE_ANIMATIONS[exerciseId];
  }

  // Fallback to closest muscle group archetype
  if (exerciseId.includes('curl')) return BICEP_CURL_ANIMATION;
  if (exerciseId.includes('press') || exerciseId.includes('push')) return BENCH_PRESS_ANIMATION;
  if (exerciseId.includes('pulldown') || exerciseId.includes('row')) return LAT_PULLDOWN_ANIMATION;
  if (exerciseId.includes('squat') || exerciseId.includes('lunge')) return SQUAT_ANIMATION;
  if (exerciseId.includes('raise') || exerciseId.includes('delt')) return LATERAL_RAISE_ANIMATION;
  if (exerciseId.includes('extension') || exerciseId.includes('tricep')) return TRICEPS_PUSHDOWN_ANIMATION;
  if (exerciseId.includes('deadlift') || exerciseId.includes('rdl')) return RDL_ANIMATION;
  if (exerciseId.includes('abs') || exerciseId.includes('core')) return PLANK_ANIMATION;

  return BICEP_CURL_ANIMATION;
}
